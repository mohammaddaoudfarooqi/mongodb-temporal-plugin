#!/usr/bin/env bash
# One-command deploy for the MongoDB Temporal plugin.
#
# Usage:
#   ./deploy.sh                                  # self-hosted Mongo 8 replica set (default)
#   ./deploy.sh --atlas "<ATLAS_SRV_URI>"        # target a MongoDB Atlas cluster (Linux only)
#   ./deploy.sh --namespace <name>[,<name>,...]  # register namespaces after startup (repeatable)
#   ./deploy.sh --down                           # tear down everything
#   ./deploy.sh --status                         # show service status + URLs
#   ./deploy.sh --logs [service]                 # tail logs (default: temporal server)
#   ./deploy.sh --health                         # run connectivity + error checks
#   ./deploy.sh --help
#
# Common combinations:
#   ./deploy.sh --namespace my-namespace
#   ./deploy.sh --atlas '<URI>' --namespace my-namespace   # Linux only
#   ./deploy.sh --namespace ns-a,ns-b,ns-c
#
# Platform notes:
#   macOS / Windows: Docker Desktop runs containers inside a VM whose NAT
#     bridge corrupts long-lived TCP connections to external hosts.
#     Atlas mode is BLOCKED on these platforms. Use local MongoDB (default).
#   Linux: native Docker has no VM layer; Atlas works reliably.
#
# What it does:
#   1. Detects the host platform and blocks unsafe configurations.
#   2. Builds the plugin container image from the repo root Dockerfile.
#   3. Renders env defaults into a local `.env` file the compose uses.
#   4. Starts Mongo (self-hosted) or skips it (Atlas), initializes the
#      replica set, runs `temporal-mongodb-tool setup-schema` for the
#      temporal database (both stores), then starts the plugin
#      server + Temporal Web UI.
#   5. Waits until the UI and gRPC endpoints respond, then prints how
#      to reach them.
#   6. Registers any requested namespaces via the HTTP API.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

PLUGIN_IMAGE_TAG="${PLUGIN_IMAGE_TAG:-temporal-mongodb-plugin:local}"

usage() {
    sed -n '2,35p' "$0" | sed 's/^# \{0,1\}//'
}

say() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mWARN:\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mFAIL:\033[0m %s\n' "$*" >&2; exit 1; }

require() {
    command -v "$1" >/dev/null 2>&1 || die "missing required tool: $1"
}

# --- Platform detection ---------------------------------------------------

detect_platform() {
    # Returns "linux-native", "mac-desktop", or "windows-desktop".
    # The key distinction: does Docker run natively (Linux) or inside a
    # VM (Docker Desktop on Mac/Windows)?
    local os
    os="$(uname -s)"
    case "$os" in
        Linux)
            # Could still be Docker Desktop for Linux, but that uses
            # native containerd, not a VM — Atlas works fine.
            echo "linux-native"
            ;;
        Darwin)
            echo "mac-desktop"
            ;;
        MINGW*|MSYS*|CYGWIN*|Windows_NT)
            echo "windows-desktop"
            ;;
        *)
            warn "unknown OS '$os' — assuming Docker Desktop (VM-based)"
            echo "unknown-desktop"
            ;;
    esac
}

is_docker_desktop() {
    local platform="$1"
    [[ "$platform" == "mac-desktop" || "$platform" == "windows-desktop" || "$platform" == "unknown-desktop" ]]
}

# --- Port management ------------------------------------------------------

port_in_use() {
    local port="$1"
    if command -v ss >/dev/null 2>&1; then
        ss -tln 2>/dev/null | awk '{print $4}' | grep -Eq "[:.]${port}$"
        return $?
    fi
    if command -v lsof >/dev/null 2>&1; then
        lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1
        return $?
    fi
    (exec 3<>/dev/tcp/127.0.0.1/"$port") 2>/dev/null && { exec 3<&-; exec 3>&-; return 0; }
    return 1
}

pick_free_port() {
    local start="$1"
    local p="$start"
    while port_in_use "$p"; do
        p=$((p + 1))
        if [[ $p -gt $((start + 50)) ]]; then
            die "could not find a free port in [$start, $((start + 50))]"
        fi
    done
    echo "$p"
}

# --- .env generation ------------------------------------------------------

write_env() {
    local mongo_uri="$1"
    local vis_mode="$2"
    local mongo_port="$3"
    local grpc_port="$4"
    local http_port="$5"
    local ui_port="$6"
    cat > "$SCRIPT_DIR/.env" <<EOF
# Generated by deploy.sh — do not edit by hand.
PLUGIN_IMAGE_TAG=$PLUGIN_IMAGE_TAG
TEMPORAL_MONGO_URI=$mongo_uri
TEMPORAL_VISIBILITY_MODE=$vis_mode
MONGO_HOST_PORT=$mongo_port
TEMPORAL_GRPC_PORT=$grpc_port
TEMPORAL_HTTP_PORT=$http_port
TEMPORAL_UI_PORT=$ui_port
TEMPORAL_UI_DEFAULT_NAMESPACE=${TEMPORAL_UI_DEFAULT_NAMESPACE:-temporal-system}
EOF
}

# --- Readiness gates ------------------------------------------------------

wait_for_http() {
    local url="$1"
    local name="$2"
    local timeout="${3:-120}"
    local start
    start=$(date +%s)
    while true; do
        if curl -fsS -o /dev/null --max-time 2 "$url" 2>/dev/null; then
            say "$name ready ($url)"
            return 0
        fi
        if (( $(date +%s) - start > timeout )); then
            die "$name did not become ready within ${timeout}s ($url)"
        fi
        sleep 2
    done
}

wait_for_grpc() {
    local host="$1"
    local port="$2"
    local timeout="${3:-120}"
    local start
    start=$(date +%s)
    while true; do
        if curl -fsS -o /dev/null --max-time 2 "http://$host:$port/api/v1/namespaces?pageSize=1" 2>/dev/null; then
            say "temporal HTTP API alive (http://$host:$port/api/v1/namespaces)"
            return 0
        fi
        if (( $(date +%s) - start > timeout )); then
            say "warn: HTTP API on port $port did not come up in ${timeout}s (skipping gate)"
            return 0
        fi
        sleep 2
    done
}

# --- Namespace registration -----------------------------------------------

register_namespaces() {
    local http_port="$1"
    local namespaces="$2"

    [[ -z "$namespaces" ]] && return 0

    local IFS_SAVED="$IFS"
    IFS=,
    for ns in $namespaces; do
        ns="$(echo "$ns" | tr -d '[:space:]')"
        [[ -z "$ns" ]] && continue
        say "Registering namespace: $ns"
        local resp
        resp=$(curl -sS -X POST "http://localhost:$http_port/api/v1/namespaces" \
            -H 'content-type: application/json' \
            -d "{\"namespace\":\"$ns\",\"workflowExecutionRetentionPeriod\":\"604800s\"}" 2>&1)
        if [[ "$resp" == "{}" ]]; then
            say "  registered"
        elif echo "$resp" | grep -q "already exists"; then
            say "  already exists — ok"
        else
            say "  warn: $resp"
        fi
    done
    IFS="$IFS_SAVED"
}

# --- Subcommands ----------------------------------------------------------

cmd_up() {
    local profile="$1"
    local mongo_uri="$2"
    local vis_mode="$3"
    local platform="$4"

    require docker
    docker compose version >/dev/null 2>&1 || die "docker compose v2 plugin required"

    # --- Platform safety gate ---
    if [[ "$profile" == "atlas" ]] && is_docker_desktop "$platform"; then
        if [[ "${DEPLOY_FORCE_ATLAS:-}" != "true" ]]; then
            cat >&2 <<'BLOCK'

  ╔══════════════════════════════════════════════════════════════╗
  ║  BLOCKED: Atlas mode on Docker Desktop (Mac/Windows)        ║
  ╠══════════════════════════════════════════════════════════════╣
  ║                                                             ║
  ║  Docker Desktop runs containers inside a Linux VM.          ║
  ║  The VM's NAT bridge corrupts long-lived TCP connections    ║
  ║  to external hosts like MongoDB Atlas, causing:             ║
  ║                                                             ║
  ║    • "incomplete read of message header" errors             ║
  ║    • Task queue managers stopping with InitError            ║
  ║    • Workflow tasks never reaching workers                  ║
  ║                                                             ║
  ║  Use local MongoDB instead (the default):                   ║
  ║    ./deploy.sh --namespace my-namespace                    ║
  ║                                                             ║
  ║  To override (at your own risk):                            ║
  ║    DEPLOY_FORCE_ATLAS=true ./deploy.sh --atlas '<URI>'      ║
  ║                                                             ║
  ╚══════════════════════════════════════════════════════════════╝

BLOCK
            die "Atlas mode blocked on Docker Desktop. See above."
        else
            warn "DEPLOY_FORCE_ATLAS=true — proceeding with Atlas on Docker Desktop."
            warn "Expect 'incomplete read of message header' errors and task queue failures."
        fi
    fi

    # Pick free host ports so we don't collide with other stacks.
    local mongo_port="${MONGO_HOST_PORT:-$(pick_free_port 27017)}"
    local grpc_port="${TEMPORAL_GRPC_PORT:-$(pick_free_port 7233)}"
    local http_port="${TEMPORAL_HTTP_PORT:-$(pick_free_port 7243)}"
    local ui_port="${TEMPORAL_UI_PORT:-$(pick_free_port 8080)}"

    say "Platform: $platform"
    say "Mode: $profile (MongoDB $([ "$profile" = "local" ] && echo "8.0 replica set" || echo "Atlas"))"
    say "Building plugin image: $PLUGIN_IMAGE_TAG"
    (cd "$REPO_ROOT" && docker build -t "$PLUGIN_IMAGE_TAG" .)

    # First namespace from the list is also the UI's default namespace.
    local ui_default_ns="${TEMPORAL_UI_DEFAULT_NAMESPACE:-}"
    if [[ -z "$ui_default_ns" && -n "$NAMESPACES" ]]; then
        ui_default_ns="$(echo "$NAMESPACES" | cut -d, -f1 | tr -d '[:space:]')"
    fi
    export TEMPORAL_UI_DEFAULT_NAMESPACE="${ui_default_ns:-temporal-system}"

    say "Writing $SCRIPT_DIR/.env (mongo=$mongo_port, grpc=$grpc_port, http=$http_port, ui=$ui_port, ui_default_ns=$TEMPORAL_UI_DEFAULT_NAMESPACE)"
    write_env "$mongo_uri" "$vis_mode" "$mongo_port" "$grpc_port" "$http_port" "$ui_port"

    say "docker compose up -d --profile $profile"
    cd "$SCRIPT_DIR"
    if [[ "$profile" == "local" ]]; then
        docker compose --profile local up -d
    else
        docker compose --profile atlas up -d
    fi

    wait_for_http "http://localhost:$ui_port" "Temporal UI" 240
    wait_for_grpc "localhost" "$http_port" 180

    register_namespaces "$http_port" "$NAMESPACES"

    cat <<EOF

--------------------------------------------------------------------
MongoDB Temporal plugin deployed.

  Temporal UI:         http://localhost:$ui_port
  Temporal gRPC:       localhost:$grpc_port
  Temporal HTTP API:   http://localhost:$http_port
EOF
    if [[ "$profile" == "local" ]]; then
        echo "  MongoDB:             mongodb://localhost:$mongo_port (replica set rs0)"
    else
        echo "  MongoDB:             (Atlas) $mongo_uri"
    fi
    cat <<EOF

Stop:    ./deploy.sh --down
Status:  ./deploy.sh --status
Logs:    ./deploy.sh --logs
Health:  ./deploy.sh --health
--------------------------------------------------------------------
EOF
}

cmd_down() {
    require docker
    cd "$SCRIPT_DIR"
    say "docker compose down -v (removes containers + mongo volume)"
    docker compose --profile local --profile atlas down -v --remove-orphans || true
    rm -f "$SCRIPT_DIR/.env"
    say "tear-down complete"
}

cmd_status() {
    cd "$SCRIPT_DIR"
    docker compose ps 2>/dev/null || echo "compose stack not up."
    if [[ -f "$SCRIPT_DIR/.env" ]]; then
        echo ""
        echo "Endpoints (from $SCRIPT_DIR/.env):"
        awk -F= '
            /^TEMPORAL_UI_PORT=/    { printf "  Temporal UI:       http://localhost:%s\n", $2 }
            /^TEMPORAL_GRPC_PORT=/  { printf "  Temporal gRPC:     localhost:%s\n", $2 }
            /^TEMPORAL_HTTP_PORT=/  { printf "  Temporal HTTP:     http://localhost:%s\n", $2 }
            /^MONGO_HOST_PORT=/     { printf "  MongoDB (local):   mongodb://localhost:%s\n", $2 }
        ' "$SCRIPT_DIR/.env"
    fi
}

cmd_logs() {
    local service="${1:-temporal}"
    cd "$SCRIPT_DIR"
    case "$service" in
        temporal|server) docker compose logs -f temporal ;;
        ui)              docker compose logs -f temporal-ui ;;
        mongo)           docker compose logs -f mongo ;;
        schema)          docker compose logs schema-init ;;
        all)             docker compose logs -f ;;
        *)               die "unknown service: $service (try: temporal, ui, mongo, schema, all)" ;;
    esac
}

cmd_health() {
    cd "$SCRIPT_DIR"
    local issues=0

    echo "=== Health Check ==="
    echo ""

    # 1. Container status
    echo "--- Containers ---"
    local server_status
    server_status=$(docker inspect -f '{{.State.Health.Status}}' temporal-server 2>/dev/null || echo "not-found")
    if [[ "$server_status" == "healthy" ]]; then
        echo "  temporal-server: healthy"
    else
        echo "  temporal-server: $server_status"
        issues=$((issues + 1))
    fi

    local mongo_status
    mongo_status=$(docker inspect -f '{{.State.Health.Status}}' temporal-mongo 2>/dev/null || echo "not-running")
    echo "  temporal-mongo:  $mongo_status"

    local ui_running
    ui_running=$(docker inspect -f '{{.State.Running}}' temporal-ui 2>/dev/null || echo "false")
    echo "  temporal-ui:     $([ "$ui_running" = "true" ] && echo "running" || echo "not-running")"

    echo ""

    # 2. MongoDB errors in last 60s
    echo "--- MongoDB errors (last 60s) ---"
    local incomplete_count
    incomplete_count=$(docker logs temporal-server --since 60s 2>&1 | grep -c "incomplete read" || true)
    local incomplete_noncanceled
    incomplete_noncanceled=$(docker logs temporal-server --since 60s 2>&1 | grep "incomplete read" | grep -cv "context canceled" || true)
    local init_error_count
    init_error_count=$(docker logs temporal-server --since 60s 2>&1 | grep -c "InitError" || true)

    if [[ "$incomplete_noncanceled" -gt 0 ]]; then
        echo "  incomplete read errors: $incomplete_count ($incomplete_noncanceled non-cancellation)"
        echo "  DIAGNOSIS: TCP connection corruption. If on Docker Desktop (Mac/Windows)"
        echo "             with Atlas, switch to local MongoDB: ./deploy.sh --down && ./deploy.sh"
        issues=$((issues + 1))
    elif [[ "$incomplete_count" -gt 0 ]]; then
        echo "  incomplete read errors: $incomplete_count (all context-canceled — benign)"
        echo "  NOTE: These occur during normal task queue drain cycles and do not"
        echo "        affect functionality. The MongoDB Go driver v2 reports context"
        echo "        cancellation as 'incomplete read' when a read is interrupted."
    else
        echo "  incomplete read errors: 0"
    fi

    if [[ "$init_error_count" -gt 0 ]]; then
        echo "  task queue InitError:   $init_error_count (task queues restart automatically)"
    else
        echo "  task queue InitError:   0"
    fi

    echo ""

    # 3. gRPC API check
    echo "--- gRPC API ---"
    if [[ -f "$SCRIPT_DIR/.env" ]]; then
        local http_port
        http_port=$(awk -F= '/^TEMPORAL_HTTP_PORT=/ {print $2}' "$SCRIPT_DIR/.env")
        if curl -fsS -o /dev/null --max-time 3 "http://localhost:$http_port/api/v1/namespaces?pageSize=1" 2>/dev/null; then
            echo "  HTTP API: responding on port $http_port"
        else
            echo "  HTTP API: NOT responding on port $http_port"
            issues=$((issues + 1))
        fi
    else
        echo "  no .env found — stack may not be running"
        issues=$((issues + 1))
    fi

    echo ""
    if [[ "$issues" -eq 0 ]]; then
        echo "=== All checks passed ==="
    else
        echo "=== $issues issue(s) found ==="
    fi
    return "$issues"
}

# --- Main -----------------------------------------------------------------

main() {
    local atlas_uri=""
    local subcommand=""
    local log_service=""
    NAMESPACES="${TEMPORAL_NAMESPACES:-}"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --namespace|--namespaces)
                shift
                [[ $# -ge 1 ]] || die "--namespace requires a value (comma-separated for multiple)"
                if [[ -n "$NAMESPACES" ]]; then
                    NAMESPACES="$NAMESPACES,$1"
                else
                    NAMESPACES="$1"
                fi
                shift
                ;;
            --atlas)
                shift
                [[ $# -ge 1 ]] || die "--atlas requires a URI: ./deploy.sh --atlas 'mongodb+srv://...'"
                atlas_uri="$1"
                subcommand="atlas"
                shift
                ;;
            --local|local|--up|up)
                subcommand="local"
                shift
                ;;
            --down|down)
                subcommand="down"
                shift
                ;;
            --status|status)
                subcommand="status"
                shift
                ;;
            --logs|logs)
                subcommand="logs"
                shift
                if [[ $# -gt 0 && ! "$1" =~ ^-- ]]; then
                    log_service="$1"
                    shift
                fi
                ;;
            --health|health)
                subcommand="health"
                shift
                ;;
            -h|--help|help)
                subcommand="help"
                shift
                ;;
            *)
                die "unknown arg: $1 (try --help)"
                ;;
        esac
    done

    local platform
    platform="$(detect_platform)"

    case "$subcommand" in
        help)
            usage
            ;;
        down)
            cmd_down
            ;;
        status)
            cmd_status
            ;;
        logs)
            cmd_logs "$log_service"
            ;;
        health)
            cmd_health
            ;;
        atlas)
            local vis_mode="${TEMPORAL_VISIBILITY_MODE:-aggregation}"
            cmd_up "atlas" "$atlas_uri" "$vis_mode" "$platform"
            ;;
        local|"")
            cmd_up "local" "mongodb://mongo:27017/?replicaSet=rs0" "aggregation" "$platform"
            ;;
        *)
            die "unknown arg: $1 (try --help)"
            ;;
    esac
}

main "$@"
